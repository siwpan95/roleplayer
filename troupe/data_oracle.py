#: 混沌对 logit 的斜率（每 +1 混沌，logit 向左平移 0.35）
CHAOS_SLOPE = 0.35


def fate_probability(base_p: float, chaos: int) -> float:
    """把基础概率按混沌因子平移到实际概率（logit 空间线性平移）。"""
    p = min(0.999, max(0.001, float(base_p)))
    logit = math.log(p / (1.0 - p)) - CHAOS_SLOPE * (clamp_chaos(chaos) - CHAOS_NEUTRAL)
    return 1.0 / (1.0 + math.exp(-logit))


