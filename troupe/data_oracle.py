import math

# =============================================================================
#  混沌因子
# =============================================================================
CHAOS_MIN = 1
CHAOS_MAX = 9
CHAOS_DEFAULT = 5
CHAOS_NEUTRAL = 5


def clamp_chaos(value: int) -> int:
    return max(CHAOS_MIN, min(CHAOS_MAX, int(value)))


#: 随机事件触发概率（按混沌因子）
