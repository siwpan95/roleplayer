"""troupe.data_oracle - GM 模拟器（Oracle）常量与概率模型

设计说明（重要）
----------------
本模块**不是**任何商业 GM 模拟器产品（如 Mythic GME）的表格照搬。它采用同类的
**机制思想**——混沌因子、命运问答、事件焦点、意义词表——但概率模型与全部词条均为
本项目自研，理由有三：

1. 许可干净：不复制任何受版权保护的表格与措辞。
2. 可调参：概率集中在 ``FATE_MODEL`` 一处，便于做难度曲线与平衡回归。
3. 可测试：模型是纯函数（logit 平移），能写断言验证单调性与边界。

概率模型
--------
命运问答 ``fate(odds, chaos)``：

    logit(p) = logit(base_p) - CHAOS_SLOPE * (chaos - CHAOS_NEUTRAL)

* ``chaos`` 取值 1..9，``CHAOS_NEUTRAL = 5`` 时无偏移（p = base_p）。
* 混沌越高，同样的问题越难得到肯定答复；混沌 1 时最宽松。
* 例：五五开（base 0.50）在 chaos=9 时 ≈ 0.20，在 chaos=1 时 ≈ 0.80。

随机事件：``RANDOM_EVENT_CHANCE[chaos]``，随混沌单调上升（5% → 15%）。
"""
from __future__ import annotations

import math

# =============================================================================
#  混沌因子
# =============================================================================
CHAOS_MIN = 1
CHAOS_MAX = 9
CHAOS_DEFAULT = 5
CHAOS_NEUTRAL = 5


def clamp_chaos(value: int) -> int:
    return max(CHAOS_MIN, min(CHAOS_MAX, int(value)))


#: 随机事件触发概率（按混沌因子）
