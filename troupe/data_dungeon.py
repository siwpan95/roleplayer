def roll_room_content(rnd: random.Random, treasure: bool = False) -> dict:
    """为一个房间抽取内容三件套（类型 / 危险 / 发现）。

    ``rnd`` 必须是独立的 ``random.Random(seed)`` 派生流（调用方保证），
    以保证同种子内容确定、不污染模拟器分域 RNG。
    """
    def weighted_pick(table):
        total = sum(w for w, _ in table)
        x = rnd.random() * total
        acc = 0.0
        for w, item in table:
            acc += w
            if x <= acc:
                return item
        return table[-1][1]

    rtype, rdesc = rnd.choice(DUNGEON_ROOM_TYPES)
    danger = weighted_pick(DUNGEON_DANGERS)
    if treasure:
        discovery = "这里有前人埋下的宝藏，但取走它的人没有一个善终。"
    else:
        discovery = weighted_pick(DUNGEON_DISCOVERIES)
    return {"type": rtype, "desc": rdesc, "danger": danger, "discovery": discovery}


